def normalize(s):
    """去重用的归一化：去首尾空白、折叠内部多空格、去结尾标点差异。"""
    s = s.strip()
    s = re.sub(r'\s+', ' ', s)
    return s


def main():
    # 每类目标句数：20 类 × 100 = 2000，且每句只归属一个类别，故全局恰好 2000
    TARGET = 100
    # 期望的 20 个类别（用于检测缺失类别与缺口统计）
    EXPECTED = [
        'greetings', 'introductions', 'daily_routine', 'food_dining',
        'shopping', 'transportation', 'weather', 'health',
        'family', 'work_study', 'hobbies', 'emotions',
        'requests_help', 'phone_messages', 'directions', 'time_schedule',
        'home_housework', 'travel', 'money_payment', 'small_talk',
    ]
    # 1) 剔除占位模板句（含 [PLACEHOLDER] 的视为模板，不计入真实语料）
    cleaned = [(s, c, src) for (s, c, src) in RAW if '[PLACEHOLDER]' not in s]
    # 2) 全局去重：按归一化小写句为键，保留首次出现者，类别随首次出现归属
    seen = {}
    deduped = []
    for s, c, src in cleaned:
        key = normalize(s).lower()
        if key in seen:
            continue
        seen[key] = True
        deduped.append((s, c, src))
    # 3) 按类别分组，每类只保留前 TARGET 条（顺序即 RAW 中的出现顺序）
    #    超额类别被自然截断到 100；缺口类别保留其全部真实句，稍后由缺口报告暴露
    by_cat = {}
    order = []
    for s, c, src in deduped:
        if c not in by_cat:
            by_cat[c] = []
            order.append(c)
        if len(by_cat[c]) < TARGET:
            by_cat[c].append((s, src))
    # 4) 组装输出（保持类别首次出现顺序，便于审阅）
    out = []
    now = int(time.time())
    for c in order:
        for s, src in by_cat[c]:
            out.append({
                'sentence': normalize(s),
                'category': c,
                'source_id': src,
                'source_url': SOURCES[src]['url'],
                'register': 'neutral',
                'collected_at': now,
                'notes': '',
            })
    # 5) 写文件
    os.makedirs(CORPUS, exist_ok=True)
    path = os.path.join(CORPUS, 'daily_english_2000.json')
    json.dump(out, open(path, 'w', encoding='utf-8'),
              ensure_ascii=False, indent=2)
    # 6) 统计与缺口报告
    from collections import Counter
    cnt = Counter(o['category'] for o in out)
    print(f"总句数（全局去重 + 每类上限{TARGET}）：{len(out)}")
    print(f"目标总数（{len(EXPECTED)} × {TARGET}）：{len(EXPECTED) * TARGET}")
    print("各类别数量：")
    gaps = []
    for cat in EXPECTED:
        n = cnt.get(cat, 0)
        flag = '' if n >= TARGET else '  <-- 缺口，需补'
        if n < TARGET:
            gaps.append((cat, n))
        print(f"  {cat}: {n}{flag}")
    # 不在期望列表中的意外类别
    extra = [c for c in cnt if c not in EXPECTED]
    if extra:
        print("意外类别（不在 20 类清单）：")
        for c in extra:
            print(f"  {c}: {cnt[c]}")
    print(f"缺口类别数：{len(gaps)}")
    for cat, n in gaps:
        print(f"  需补 {cat}：{TARGET - n} 句（当前 {n}）")
    # 来源计数
    scnt = Counter(o['source_id'] for o in out)
    print("各来源数量：")
    for s in SOURCES:
        print(f"  {s}: {scnt.get(s, 0)}")
    print(f"写出：{path}")


if __name__ == '__main__':
    main()
