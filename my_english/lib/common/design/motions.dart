///
/// 全 App 的动画时长刻度。
///
/// 按毫秒数命名（`ms250` 就是 250 毫秒），和间距、圆角同一套规矩。
///
/// 原来散落在各页面的 80 / 84 / 120 / 150 / 180 / 200 / 210 / 220 / 300 /
/// 400 / 600 / 1000 在「收敛」那一步并进下面六档。
///
/// 有两类时长**刻意不在这张表里**，别以为是漏了：
///
///   1. 功能计时——搜索框防抖 120 毫秒、加载超时 8 秒、提示条停留 2 秒、
///      四个模块每秒跳一次的计时器、键盘长按判定 420 毫秒与连发间隔 90 毫秒。
///      它们决定「等多久再干正事」，属于业务逻辑，跟好看不好看无关；
///      混进来的后果是哪天想让动画快一点，顺手把加载超时也改了。
///   2. 成对的节拍——闪烁光标亮 472 / 灭 578（见 `lib/widgets/blinking_caret.dart`）
///      是一个周期的 45% 和 55%，并成同一档就变成对称闪烁了。
///
abstract final class AppDuration {
  ///
  /// 100 毫秒 · 按键级反馈。
  ///
  /// 用在：
  /// - 拼写巩固 → 字母格 → 敲一个键，字母从零弹出到 1.2 倍再回落；
  /// - 拼写巩固 → 播音声纹 → 换一帧竖条的间隔（收敛前 84）；
  /// - 喇叭按钮 → 播放中声纹换帧的间隔；
  /// - 键盘 → 键帽按下缩小回弹（收敛前 80）、底色变灰（收敛前 120），
  ///   以及快速点击时按下画面至少停留的时间（收敛前 90）。
  static const int ms100 = 100;

  ///
  /// 160 毫秒 · 一步到位的小动作。
  ///
  /// 特点是「用户还没反应过来就已经做完」，所以收起类动作都放这一档。
  ///
  /// 用在：
  /// - 看义选词 → 选对候选后，整个单词一次填进字母格的浮现动画；
  /// - 首页 → 单词行左滑露出操作区（收敛前 180）；
  /// - 首页 → 单词行展开释义的高度过渡；
  /// - 首页 → 分组标题折叠箭头旋转 90 度（收敛前 150）；
  /// - 首页 → 学习悬浮菜单收起（收敛前 180，比展开快一档是刻意的）；
  /// - 首页 → 添加单词表单给弹起的键盘让位（收敛前 180）；
  /// - 提示条 → 进场与退场（收敛前 200，注意不是它停留的 2 秒）；
  /// - 听音辨义 / 拼写巩固 → 播音胶囊下方文字换字（收敛前 180）。
  static const int ms160 = 160;

  ///
  /// 250 毫秒 · 换题、换面板与变色。
  ///
  /// 用在：
  /// - 看义选词 → 换题时整张白卡淡入并轻微上移；
  /// - 词义连连 → 候选卡在默认 / 选中 / 连对 / 连错之间的变色过渡；
  /// - 词义连连 → 换组时整块棋盘淡入；
  /// - 听音辨义 → 整组候选淡出淡入（收敛前 210）；
  /// - 听音辨义 → 候选卡答错时的左右抖动（收敛前 300）；
  /// - 首页 → 学习悬浮菜单展开、最近记录横向展开（收敛前 300 / 220）；
  /// - 首页 → 词库面板从屏幕下方滑出（收敛前 300）；
  /// - 随身听 → 列表自动滚到当前行（收敛前 220）；
  /// - 喇叭按钮 → 外圈弧线的亮灭节奏。
  static const int ms250 = 250;

  ///
  /// 350 毫秒 · 变形与连线。
  ///
  /// 用在：
  /// - 词义连连 → 连对后绿色贝塞尔连线的生长；
  /// - 词义连连 → 卡片放大 1.02 / 缩小 0.97 的形变；
  /// - 词义连连 → 连错时卡片左右甩动（收敛前 400）；
  /// - 拼写巩固 → 答错时字母区左右抖动。
  static const int ms350 = 350;

  ///
  /// 800 毫秒 · 呼吸、停顿与出场。
  ///
  /// 用在：
  /// - 词义连连 → 最后 10 秒倒计时文字的一次呼吸循环；
  /// - 词义连连 → 一组五对全部连完后，切到下一组前的停顿（收敛前 600）；
  /// - 首页 → 复习趋势折线图 → 进页面后延迟多久才让节点滑上来（收敛前 600），
  ///   以及节点本身生长到位的时长（同样收敛前 600）。
  static const int ms800 = 800;

  ///
  /// 1200 毫秒 · 看清答案的停顿。
  ///
  /// 用在：
  /// - 看义选词 → 本题全部答对后，停留让用户看清刚填入的单词再切题；
  /// - 拼写巩固 → 答错后红色反馈的完整保留时间，以及答对后切下一个词的停顿
  ///   （原来 1000，收敛到这里）。
  static const int ms1200 = 1200;
}
