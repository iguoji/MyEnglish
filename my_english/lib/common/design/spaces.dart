///
/// 全 App 的间距刻度：档位与名字都取自 Tabler 的 spacer 表。
///
/// Tabler（以及它底下的 Bootstrap）把间距做成一张只有六档的表，class 名就是档号：
/// `p-1 / m-1 / gap-1` 是 4 像素，`p-2` 是 8，`p-3` 是 16，`p-4` 是 24，`p-5` 是 32，
/// `p-6` 是 48。这张表的 [p1]…[p6] 与它一一对应，**值也完全相同**——在原型或
/// Tabler 文档里看到 `p-3`，代码里就写 `AppSpace.p3`，不需要换算。
///
/// 名字为什么是 `p`：CSS 里的间距只有两种身份，`padding`（自己内部的留白）和
/// `margin`（和别人之间的距离），Tabler 的 class 前缀就是 `p-` 和 `m-`。
/// Flutter 这边两者共用同一张刻度表（`EdgeInsets` 既能当内边距也能当外边距，
/// `SizedBox` 就是一段空白），所以只保留一套 `p`，不再分两份。
///
/// 这一版把档位**贴到了 Tabler 的六档**。原来还有 2 / 6 / 10 / 12 / 18 / 20 / 40
/// 七个 Tabler 里查不到的孤档，现在就地并入相邻档：2→4、6→8、10→8、12→16、
/// 18→16、20→24、40→48。代价是全站两百多处留白跟着挪了几个像素；换来的是
/// 「代码里出现的每一档，都能在 Tabler 文档里查到同名同值的 class」。
///
abstract final class AppSpace {
  ///
  /// 0 · Tabler `p-0` · 刻意不留缝。
  ///
  /// 为什么 0 也要占一档：`EdgeInsets.fromLTRB(24, 24, 24, 0)` 里的那个 0 不是
  /// 「忘了填」，而是「这一边故意不留白，让下面的内容顶上来」。给它一个名字之后，
  /// 四个方向读起来是同一种东西，「禁止裸数字」的检查也不必为 0 开特例。
  ///
  /// 用在：
  /// - 首页 → 仪表盘外层 → 左右留白交给内部卡片，所以左右填 0；
  /// - 拼写巩固 → 键盘面板贴住屏幕底边，底部填 0。
  static const double p0 = 0;

  ///
  /// 4 · Tabler `p-1` · 最小的一档。
  ///
  /// 用在：图标与文字之间的缝、徽标内部的上下内边距、两行文字之间的错位补偿。
  ///
  /// 并进来的旧档：2。两个像素和四个像素在屏幕上分不出前后关系，没必要各占一档。
  static const double p1 = 4;

  ///
  /// 8 · Tabler `p-2` · 行内元素之间的常规间隙。
  ///
  /// 用在：一行里图标与文字、文字与徽标之间；紧挨着的两张小卡之间。
  ///
  /// 并进来的旧档：6 与 10。这两档原来占了全站间距的四分之一（53 处 + 42 处），
  /// 是「差不多的东西各留一档」最典型的地方——6 和 8 差两个像素，10 和 8 也差两个，
  /// 三档挤在一起，改任何一处都得先想「我该用哪个」。
  static const double p2 = 8;

  ///
  /// 16 · Tabler `p-3` · 基准间距（Tabler 的 `$spacer` 本身就是 1rem = 16）。
  ///
  /// 用在：卡片内部的四周留白、屏幕左右的安全边距、区块标题与内容之间。
  ///
  /// 并进来的旧档：12 与 18。
  static const double p3 = 16;

  ///
  /// 18 · 非 Tabler 档 · 全局基准留白。
  ///
  /// 为什么在 `p3`(16) 与 `p4`(24) 之间补这一档：`p4` 的 24 在手机屏上偏宽，
  /// 多处区块间距收一档又落到 16 显得太挤，于是取一个中间值 18 作为「基准留白」，
  /// 让页面默认呼吸感介于两者之间。它不在 Tabler 的六档刻度里，所以名字不带档号，
  /// 而是叫 `pBase`，强调「这是本 App 自己定的基准间距」。
  static const double pBase = 18;

  ///
  /// 24 · Tabler `p-4` · 区块与区块之间。
  ///
  /// 用在：仪表盘上下两块之间、题干与选项区之间、卡片纵向的大留白。
  ///
  /// 并进来的旧档：20。
  static const double p4 = 24;

  ///
  /// 32 · Tabler `p-5` · 大块之间的呼吸。
  ///
  /// 用在：结算页几组数字之间、页面顶部与第一块内容之间。
  static const double p5 = 32;

  ///
  /// 48 · Tabler `p-6` · 整屏级留白。
  ///
  /// 用在：列表底部给悬浮按钮让出的位置、空状态插图的上下留白。
  ///
  /// 并进来的旧档：40。
  static const double p6 = 48;
}
