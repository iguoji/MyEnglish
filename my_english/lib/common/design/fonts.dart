// material.dart 提供 FontWeight。
import 'package:flutter/material.dart';

///
/// 全 App 的字号刻度：档位与名字都取自 Tabler 的 `.fs-*`。
///
/// Tabler 的字号表就是它的六级标题：`.fs-1` = h1 = 24 像素，`.fs-2` = 20，
/// `.fs-3` = 18，`.fs-4` = 16，`.fs-5` = 14（Tabler 的正文基准），`.fs-6` = 12。
/// 数字越小字越大——这一点和间距表相反，但它是 Tabler（Bootstrap）原本的规矩，
/// 照搬比自己另发明一套更省事：在原型里看到 `fs-5`，代码里就写 `AppFont.fs5`。
///
/// 这一版把档位贴到了这张表，原来的 10 与 28 两个孤档并入相邻档：10→12、28→24。
/// [fs2]（20）Tabler 有、本应用目前一处都没用到，所以表里先不列——将来要用，
/// 照 Tabler 补一行 `static const double fs2 = 20;` 即可。
///
/// 老年版怎么放大：不是改这里的数值，而是在 App 根上拧一个全局文字缩放器
/// （`TextScaler`，见 `lib/app.dart`），所有文字按同一比例放大，这张表一个字都不用动。
/// 所以名字里带数字不会骗人——14 永远是「设计上的 14」，屏幕上多大由缩放器决定。
///
abstract final class AppFont {
  ///
  /// 12 · Tabler `.fs-6` · 最小的一档：标签、徽标、单位、辅助说明。
  ///
  /// 用在：
  /// - 结算页统计卡 → 每格第 1 行的标签与最下面一行的单位（「次」「个单词」）；
  /// - 播音胶囊 → 右侧状态文字（「美式 · 点击播放」）；
  /// - 首页 → 单词列表每行右侧的日期、打卡热力图的图例；
  /// - 词性及含义面板 → 词性徽标、面板标题。
  ///
  /// 并进来的旧档：10。10 和 12 在手机上都属于「得凑近看」的字号，分两档没意义。
  static const double fs6 = 12;

  ///
  /// 14 · Tabler `.fs-5`，同时是 Tabler 的正文基准（`$font-size-base`）· 全站默认字号。
  ///
  /// 用在：
  /// - 听音辨义 → 底部候选卡文字；
  /// - 首页 → 单词列表的拼写与释义；
  /// - 各模块 → 结算页与题干下方的按钮文字；
  /// - 全站 Toast 与 SnackBar 文案。
  static const double fs5 = 14;

  ///
  /// 16 · Tabler `.fs-4` · 稍大正文：需要一眼看清的数字与单词。
  ///
  /// 用在：
  /// - 四个模块 → 顶栏正中的「第几个 / 总数」、右上角计时；
  /// - 看义选词 → 底部候选按钮里的英文单词；
  /// - 首页 → 添加单词表单的输入框内文字。
  static const double fs4 = 16;

  ///
  /// 18 · Tabler `.fs-3` · 页内小标题。
  ///
  /// 用在：听音辨义 → 中央标题「这个单词是？」、完成态标题「听音辨义完成」。
  static const double fs3 = 18;

  ///
  /// 24 · Tabler `.fs-1`（= h1）· 页面级标题与大字题干。
  ///
  /// 用在：
  /// - 首页 → 顶部问候语；
  /// - 四个模块 → 结算页主标题、统计卡里的 mm:ss 用时；
  /// - 看义选词 → 白卡中央的中文释义大字；
  /// - 听音辨义 → 字母瓷砖里的字母。
  ///
  /// 并进来的旧档：28。
  static const double fs1 = 24;

  ///
  /// 40 · Tabler / Bootstrap 的 `.display-6`（2.5rem）· 全站最大号。
  ///
  /// 为什么不叫 `fs0`：Tabler 的 `.fs-*` 只到 24 为止，比标题还大的字归另一族
  /// class 管（`.display-1` 到 `.display-6`，从 80 递减到 40），40 正好是最小的
  /// 那一档。名字跟着它，才查得到出处。
  ///
  /// 用在：听音辨义 → 顶部的大号英文单词；结算页统计卡 → 每格中间的主数值。
  static const double display6 = 40;
}

///
/// 全 App 的字重刻度：名字取自 Tabler 的 `.fw-*`。
///
/// Tabler 有 `.fw-light`(300) / `.fw-normal`(400) / `.fw-medium`(500) /
/// `.fw-semibold`(600) / `.fw-bold`(700)。本应用只用得上其中三档，
/// 原来散落的 w500 / w600 / w700 / `FontWeight.bold` 都已按这三档归位。
///
abstract final class AppWeight {
  ///
  /// 400 · Tabler `.fw-normal` · 正文字重。
  ///
  /// 用在：全部正文、释义、提示文案。
  static const FontWeight normal = FontWeight.w400;

  ///
  /// 600 · Tabler `.fw-semibold` · 标签、按钮、候选词。
  ///
  /// 用在：顶栏数字进度、结算页按钮文字、候选卡序号、字母格里的字母。
  static const FontWeight semibold = FontWeight.w600;

  ///
  /// 700 · Tabler `.fw-bold` · 大标题与大数字。
  ///
  /// 用在：听音辨义的大号单词、看义选词的中文释义大字、结算页主标题与主数值。
  static const FontWeight bold = FontWeight.w700;
}

///
/// 全 App 的行距：名字取自 Tabler 的 `.lh-*`。
///
/// 生活化解释：字号管一个字有多大，这张表管**行与行之间有多松**。同样 14 像素的
/// 一段话，行距 1.0 挤成一坨，行距 1.43 才读得下去。
///
/// Tabler 有 `.lh-1`（1）、`.lh-sm`（1.25）、`.lh-base`（正文基准）、`.lh-lg`（2）。
/// 本应用用前三档；`.lh-lg` 那么松的场合一处都没有，所以不列。
///
/// 为什么必须显式写出来：Flutter 的 Material 主题给每个文字槽位垫的行距各不相同
/// （1.12 到 1.5 都有），那套数字既不在这张表里也不在页面尺寸表里，谁也说不出某一
/// 行字的行高凭什么是 1.29。收进来之后，全站行距只在这张表里定。
///
/// 字距不在这张表里：全站默认不加字距，唯一一处刻意拉宽的写在它自己的页面尺寸表
/// 里（见本文件末尾那段说明）。
///
abstract final class AppLine {
  ///
  /// 1 · Tabler `.lh-1` · 行盒高度正好等于字号，上下一点余量都不留。
  ///
  /// 只给**单个字符**用——拼写巩固的字母格、单词行右边的难度徽章。它们四周的空隙
  /// 由格子自己的内边距决定，再留行距只会把字顶偏。多字符的文字不要用这一档：
  /// 字号一大，下伸笔画（g、y、p 的尾巴）会被行盒切掉。
  static const double lh1 = 1;

  ///
  /// 1.25 · Tabler `.lh-sm` · 紧凑：写死了高度的单行，以及会换行的大标题。
  ///
  /// 用在：搜索框、输入框、结算页的大数字、听音辨义的候选词、仪表盘卡片标题。
  ///
  /// 并进来的旧档：1.2 与 1.3。收敛前它们散在八处，值分别是 1.2、1.18、1.28、
  /// 1.3、1.35——做的是同一件事，差别小到看不出来。
  static const double lhSm = 1.25;

  ///
  /// 1.43 · Tabler `.lh-base` · 默认档：正文与所有会换行的中文段落。
  ///
  /// 1.43 就是 Tabler 的正文行距（20 ÷ 14）。主题里 15 个文字槽位全都带着它，
  /// 所以页面不写 `height:` 时拿到的就是这一档。
  ///
  /// 并进来的旧档：1.5（原来给大段中文释义用）。1.43 与 1.5 在 14 像素的字上
  /// 每行差不到一个像素。
  static const double lhBase = 1.43;

  // 「统一字距 0.25」这一档已经删除。它原本抄的是 Material 正文槽位的默认值，
  // 15 个文字槽位全带着它——可 0.25 像素肉眼分辨不出来，反而逼出了另一个毛病：
  // 好几处页面觉得「这里不该有字距」，于是各写一遍 `letterSpacing: 0` 去关掉它，
  // 一个看不见的默认值养出了八处看得见的抵消代码。现在默认就是不加字距，
  // 那八处抵消也一并删掉了。
  //
  // 全站只剩一处真的调字距：拼写巩固的播放状态标签（`playbackLabelLetterSpacing`
  // 1.2），那一档是原型刻意把字拉开的效果，一眼就能看出来，所以留下。
}
