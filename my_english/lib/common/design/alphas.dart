///
/// 全 App 的透明度刻度。
///
/// 透明度按数值命名（`a10` 就是 10%，写进代码是 0.10），理由和间距、圆角一样：
/// 它是纯造型参数，改值就该连名字一起改。名字里的数字统一读成百分比，
/// 不带小数点也不带前导零，`a8` 就是 8%。
///
/// 台阶全部是偶数百分比。原来散落的 6 / 13 / 25 / 35 / 45 / 55 这些孤值，
/// 在这一步分别并进 8 / 14 / 24 / 36 / 44 / 56；同一个 10% 过去还有 `0.1`
/// 和 `0.10` 两种写法，现在只剩一档。
///
/// 这张表管两类东西：`Color.withValues(alpha:)` 兑出来的淡色（底色、描边、
/// 阴影、弱化文字），以及 `Opacity` 组件让整块内容变淡的比例——两者在设计稿里
/// 本来就是同一个概念（CSS 的 `opacity` 与 `rgba()` 的第四位），所以共用一套台阶。
///
/// 不管的是**动画每一帧算出来的透明度**：单词行声纹的正弦波、字母格回弹的淡入
/// 曲线，它们的 0.15 / 0.85 是波形参数而不是某一档样式，写死在各自的动画代码里
/// 更好读，也不该被别处改这张表时顺手带走。
///
abstract final class AppAlpha {
  ///
  /// 0 · 完全透明。
  ///
  /// 单独列一档而不是直接写 0，是因为它出现在渐变的末端：那里读到「透明」
  /// 比读到一个 0 更容易看出这是「淡出到看不见」而不是漏填了数值。
  ///
  /// 用在：
  /// - 首页 → 趋势图 → 曲线下方渐变的底端；
  /// - 词性及含义面板 → 那份只用来量高度、不给人看的「尺子」文字。
  static const double none = 0;

  ///
  /// 8% · 状态染色底，最淡的一档。
  ///
  /// 收敛前这一档写过 0.06 / 0.08 两种值。这一档的作用是「几乎还是白的，
  /// 但能看出色调」，深色主题下同样成立，不会突然发白。
  ///
  /// 用在：
  /// - 听音辨义 → 点错的候选卡底色；
  /// - 随身听 → 播放列表里当前正在播的那一行底色；
  /// - 看义选词 → 结算页薄弱词标签底色；
  /// - 词义连连 → 卡片连对 / 连错后的淡底（收敛前是 0.06）。
  static const double a8 = 0.08;

  ///
  /// 10% · 淡底与聚焦光圈，全站最常用的一档（收敛后 10 处）。
  ///
  /// 收敛前这一档还混着 `0.1` 的简写，同一个浓度在代码里有两种长相。
  ///
  /// 用在：
  /// - 听音辨义 → 答案条底色、点错候选卡的序号徽标底色；
  /// - 首页 → 学习按钮展开后「继续」的底色；
  /// - 看义选词 → 「选择对应的单词」标签底色、答对候选卡底色；
  /// - 三个模块 → 结算页顶部那个圆形图标底盘（词义连连 / 拼写巩固 / 看义选词）；
  /// - 字母格 → 聚焦时下划线外那圈淡色光圈；
  /// - 词性及含义面板 → 聚焦时下划线外那圈淡色光圈。
  static const double a10 = 0.10;

  ///
  /// 12% · 更淡的投影与空闲底色。
  ///
  /// 用在：
  /// - 首页 → 学习按钮展开后「继续」的投影；
  /// - 播音胶囊 → 空闲状态的浅色底（听音辨义与拼写巩固共用同一个组件）。
  static const double a12 = 0.12;

  ///
  /// 14% · 徽标与标签底色。
  ///
  /// 收敛前这一档写过 0.13 / 0.14 两种值，同样是「淡色底 + 同色文字」的徽标，
  /// 却分了两个浓度。
  ///
  /// 用在：
  /// - 首页 → 单词行右侧难度徽标底色（收敛前是 0.13）；
  /// - 首页 → 复习模式卡右上角徽标底色（收敛前是 0.13）；
  /// - 拼写巩固 → 结算页薄弱词标签底色（收敛前是 0.13）；
  /// - 看义选词 → 答对候选卡的序号徽标底色。
  static const double a14 = 0.14;

  ///
  /// 20% · 常规投影。
  ///
  /// 用在：
  /// - 首页 → 学习按钮展开面板的黑色投影；
  /// - 词义连连 → 选中卡片向下扩散的彩色柔光。
  static const double a20 = 0.20;

  ///
  /// 22% · 细分隔线与波纹起点。
  ///
  /// 用在：
  /// - 首页 → 词库抽屉 → 「继续 / 重新开始」之间的竖分隔线；
  /// - 播音胶囊 → 两圈扩散波纹刚冒出来时的浓度（随后按进度线性淡出到透明）。
  static const double a22 = 0.22;

  ///
  /// 24% · 渐变起点与错误光晕。
  ///
  /// 收敛前两处都写 0.25。
  ///
  /// 用在：
  /// - 首页 → 趋势图 → 曲线下方渐变的顶端；
  /// - 词义连连 → 连错时锚点外圈的那层红色薄雾。
  static const double a24 = 0.24;

  ///
  /// 28% · 淡色描边。
  ///
  /// 用在：
  /// - 首页 → 学习按钮展开后「继续」的外框。
  static const double a28 = 0.28;

  ///
  /// 30% · 选中光晕。
  ///
  /// 用在：
  /// - 词义连连 → 选中时锚点外圈那圈最亮最大的光晕。
  static const double a30 = 0.30;

  ///
  /// 36% · 已完成状态的淡色。
  ///
  /// 收敛前两处都写 0.35。
  ///
  /// 用在：
  /// - 词义连连 → 连对后卡片的淡色描边（兑到卡片底色上，不再喧宾夺主）；
  /// - 拼写巩固 → 已填字母下方那条下划线的颜色。
  static const double a36 = 0.36;

  ///
  /// 42% · 主按钮的彩色投影。
  ///
  /// 用在：
  /// - 首页 → 右下角学习悬浮按钮的彩色投影。
  static const double a42 = 0.42;

  ///
  /// 44% · 已完成 / 已消解 / 不可用的中等淡化。
  ///
  /// 收敛前五处都写 0.45。
  ///
  /// 用在：
  /// - 听音辨义 → 题目卡顶部步骤条里已经走完的那几段；
  /// - 词义连连 → 连错后卡片的淡色描边（兑到卡片底色上）；
  /// - 词义连连 → 连对后整张卡片一起变淡；
  /// - 首页 → 单词表单 → 还没填够内容时，底部两个提交按钮整体变淡。
  static const double a44 = 0.44;

  ///
  /// 56% · 同色描边与禁用态。
  ///
  /// 收敛前两处都写 0.55。
  ///
  /// 用在：
  /// - 听音辨义 → 答案条外圈的同色描边；
  /// - 虚拟键盘 → 不能输入时整块键盘变淡。
  static const double a56 = 0.56;

  ///
  /// 70% · 弱化文字。
  ///
  /// 用在：
  /// - 听音辨义、拼写巩固 → 播音胶囊右侧「口音 · 状态」那行小字。
  static const double a70 = 0.70;

  ///
  /// 80% · 呼吸动画最淡处。
  ///
  /// 用在：
  /// - 词义连连 → 等待连线时，卡片一呼一吸里最淡的那一刻。
  static const double a80 = 0.80;
}
