///
/// 全 App 的图标尺寸刻度。
///
/// 只管「**多大**」。图标「**画什么**」在隔壁 `glyphs.dart` 的 `AppGlyph` 里，
/// 两张表要配合着用：一个按钮上的图标从 `AppGlyph` 取图形、从本表取尺寸。
///
/// 按数值命名（`i16` 就是 16 逻辑像素），和间距、圆角同一套规矩。图标不跟随
/// 老年版的文字放大器，所以它的数值是稳定的，名字写数值不会骗人。
///
/// 台阶全部是偶数。原来散落的 13 / 15 / 17 / 19 / 21 / 34 这些孤值，
/// 在「收敛」那一步分别并进 14 / 16 / 20 / 32。
///
/// 管的是 `Icon` 的 `size`、`AudioSpeakerButton` 的 `iconSize`，以及页面尺寸表里
/// 那些名字带 `IconSize` 的常量。**不管**圆形按钮的直径——`AudioSpeakerButton`
/// 的 `size`（默认 40、听音辨义中央那颗 88）和顶栏的 `headerButtonSize`（34）
/// 都是「按钮多大」而不是「图标多大」，它们跟着造型尺寸走。
///
abstract final class AppIcon {
  // 12 这一档已经删除。它唯一的使用者是听音辨义早期「纵向步骤条」里圆点中间的
  // 那个小勾（`ListeningMeaningLayout.stepIconSize`），那条步骤条整块下线之后，
  // 12 就成了一个谁都不用的台阶——留着只会让人以为界面上还有这么小的图标。
  //
  // 现在最小的图标是 14。

  ///
  /// 14 · 行内提示图标。
  ///
  /// 用在：
  /// - 拼写巩固 → 拼写区下方状态行 → 「✕ 拼写有误」「✓ 拼写正确」的图标；
  /// - 拼写巩固 / 词义连连 → 结算页统计卡 → 每格第 1 行标签左侧的小图标（收敛前 13）；
  /// - 首页 → 分组标题行 → 全选复选框里的白勾（收敛前 13）、右侧折叠箭头；
  /// - 首页 → 单词列表每行 → 多选复选框里的白勾（收敛前 13）；
  /// - 首页 → 排序条 → 排序方向箭头（收敛前 13）；
  /// - 首页 → 分组筛选条 → 下拉箭头、下拉菜单里当前项的勾；
  /// - 首页 → 打卡卡片 → 连续天数右侧的火苗；
  /// - 首页 → 单词表单 → 释义卡片里删掉某一条含义的叉；
  /// - 随身听 → 播放列表每行 → 正在播放时的音量图标；
  /// - 随身听 → 播放列表工具栏 → 32 见方的滚动按钮里的图标。
  static const double i14 = 14;

  ///
  /// 16 · 正文级图标。
  ///
  /// 用在：
  /// - 听音辨义 → 难度提示横幅 → 左侧警示 / 成功图标；
  /// - 听音辨义 → 底部「再试一次 / 下一题 / 完成」按钮内的图标（收敛前 17）；
  /// - 听音辨义 → 「换一个候选词」确认弹窗 → 取消与确认按钮内的图标；
  /// - 四个模块 → 结算页底部主按钮里的「再来一组」旋转箭头（收敛前 18）；
  /// - 随身听 → 搜索框前缀放大镜、上一个 / 下一个文字按钮里的方向箭头；
  /// - 随身听 → 倍速 / 间隔的加减步进按钮（28 见方，收敛前 15）；
  /// - 首页 → 抽屉菜单 → 每一项左侧图标、导入入口的云图标（收敛前都是 17）；
  /// - 首页 → 抽屉 → 每日目标与词义连连时长的加减步进按钮（收敛前 15）；
  /// - 首页 → 抽屉 → 顶部明暗切换的太阳 / 月亮、「添加单词」按钮里的加号、
  ///   页脚的 GitHub 与邮箱（三处收敛前都是 18）；
  /// - 首页 → 打卡卡片 → 上一月 / 下一月箭头（收敛前 18）；
  /// - 首页 → 学习悬浮按钮 → 书本与叉叉（收敛前 18）、展开后每一项左侧图标、
  ///   「继续」项的小三角（收敛前 15）；
  /// - 首页 → 单词表单 → 「添加释义」的加号、删除释义的垃圾桶（收敛前都是 17）；
  /// - 首页 → 词库抽屉 → 每行右侧「继续」的小三角（收敛前 17）。
  static const double i16 = 16;

  ///
  /// 20 · 顶栏与主操作图标。
  ///
  /// 用在：
  /// - 四个学习模块 → 顶栏左上角返回键（`headerIconSize`，收敛前 21）；
  /// - 随身听 / 听音辨义 → 顶栏固定画布图标按钮（收敛前 21）；
  /// - 拼写巩固 → 键盘第三行删除键的退格图标（收敛前 21）；
  /// - 拼写巩固 / 听音辨义 → 播音胶囊里的扬声器（`playbackIconSize`，
  ///   也是 `AudioSpeakerButton.iconSize` 的默认值）；
  /// - 听音辨义 → 「换一个候选词」确认弹窗标题左侧的刷新图标；
  /// - 看义选词 → 结算页统计卡标签左侧图标；
  /// - 首页 → 顶栏右上角的三横线抽屉键；
  /// - 首页 → 搜索框前缀放大镜；
  /// - 首页 → 单词表单顶部右侧的关闭叉；
  /// - 首页 → 仪表盘复习模式网格 → 每格左上角图标；
  /// - 首页 → 词库抽屉 → 每行左侧图标（收敛前 19）。
  static const double i20 = 20;

  ///
  /// 24 · 大图标。
  ///
  /// 用在：
  /// - 拼写巩固 / 词义连连 → 结算页 → 圆形底盘里的礼花 / 奖杯
  ///   （`summaryAvatarIconSize`；看义选词现在还是 32，等第 6 步统一到
  ///   拼写巩固基准时并到这一档）；
  /// - 随身听 → 底部播放控制条 → 54 见方主按钮里的播放 / 暂停。
  static const double i24 = 24;

  ///
  /// 32 · 主视觉图标。
  ///
  /// 用在：
  /// - 听音辨义 → 听音阶段中央 88 圆形播放按钮里的扬声器（收敛前 34）；
  /// - 听音辨义 → 完成态中央的绿色对勾圆盘；
  /// - 看义选词 → 结算页圆形底盘里的图标（第 6 步会并到 `i24`）。
  static const double i32 = 32;
}
