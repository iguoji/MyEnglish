///
/// 全 App 的投影刻度。
///
/// 投影按角色命名，理由和 `AppSize` 一样：同一个数字在不同角色上是不同的设计
/// 决定，只有**两个以上地方必须保持一致**的那几档才收进这张总表。
///
/// 这张表只管投影的**几何**——往下沉多少、晕开多远，不管颜色。投影的颜色跟着
/// 明暗主题走，所以留在 `colors.dart` 的 `AppTokens` 里；这里只有长度。
///
/// 生活化解释：全站的卡片投影其实只有两种手感。
///
/// - **「浮起来的一张纸」**：往下沉一点、边缘晕开一圈，看着离页面高一层。
///   候选词卡、播音胶囊、答案卡都是这一种，用 [cardOffsetY] + [cardBlur]。
/// - **「凸起来的一颗键」**：往下沉一点，但**完全不晕开**，只留一条硬边细线。
///   键盘键帽、字母格下划线的聚焦光圈是这一种，用 [cardOffsetY] + [none]。
///
/// 两种手感差的只是「晕不晕开」这一个数，所以收在同一张表里，一眼能看出
/// 它们是一组对照而不是两处巧合。
///
abstract final class AppShadow {
  ///
  /// 0 · 完全不扩散。
  ///
  /// 常规投影会向四周晕开一片，那是「这张纸浮在上面」的感觉；键帽、下划线光圈
  /// 要的是「这是一个凸起的实体」，所以刻意不晕开，只留一条实边。
  ///
  /// 单独列一档而不是直接写 0，是为了让「这里刻意不要扩散」这句话留在表里，
  /// 免得以后有人以为漏填了数值。
  ///
  /// 用在：
  /// - 虚拟键盘 → 键帽下沿那道立体感细线；
  /// - 字母格 → 聚焦时下划线外那圈光圈；
  /// - 词性及含义面板 → 聚焦时下划线外那圈光圈。
  static const double none = 0;

  ///
  /// 1 · 投影往下偏移的距离，全站统一只沉一个像素。
  ///
  /// 数值和一根细线的粗细（`AppStroke.thin`）相同，但它们不是同一件事：线宽描述
  /// 「画笔多粗」，这一档描述「影子落在下方多远」。真并成一档，以后想把描边加粗，
  /// 全站的投影会莫名跟着往下掉。
  ///
  /// 用在：听音辨义、拼写巩固、词义连连、看义选词的卡片与胶囊投影，
  /// 以及虚拟键盘的键帽投影。
  static const double cardOffsetY = 1;

  ///
  /// 2 · 卡片投影的扩散范围。
  ///
  /// 和 [cardOffsetY] 是一对：原型里所有卡片写的都是同一句
  /// `box-shadow: 0 1px 2px …`，四个复习模块各抄了一遍。收成一档之后，
  /// 想让全站卡片浮得更高只需要改这里。
  ///
  /// 用在：听音辨义 → 播音胶囊；拼写巩固 → 播音胶囊、结算页统计卡；
  /// 词义连连 → 顶部卡片、候选词卡；看义选词 → 聊天气泡、候选词卡。
  static const double cardBlur = 2;
}
