///
/// 全 App 的圆角与线宽刻度。
///
/// 圆角的名字取自 Tabler（Bootstrap）的 `.rounded-*`：一档基准叫 [rounded]，
/// 往小一档加 `Sm`，往大依次加 `Lg` / `Xl` / `Xxl`，两端全圆的那种叫
/// [roundedPill]。对应到 SCSS 变量就是 `$border-radius-sm`、`$border-radius`、
/// `$border-radius-lg`、`$border-radius-xl`、`$border-radius-xxl`、
/// `$border-radius-pill`——在原型里看到 `rounded-pill`，代码里就写 `roundedPill`。
///
/// 为什么这张表**不像间距表那样把数值也贴过去**：Tabler 的 `.rounded-1` /
/// `.rounded-2` 这几个 class，名字里的数字是「第几档」而不是「几个像素」
/// （`.rounded-2` 是 6 像素，不是 2 像素）。所以圆角只能借它的**词序**
/// （sm 比基准小、lg 比基准大），借不了数字；本表的像素值仍是原型量出来的那一套。
///
/// 台阶全部是偶数，一共五档加一个胶囊。原来散落的 1 / 3 / 4 / 5 / 7 / 9 / 15 / 23
/// 在更早的「收敛」那一步已经并进 2 / 6 / 8 / 14 / 20；这一轮改名又顺手并掉了
/// 10 与 12 两个孤档（10→8、12→14，各挪两个像素，卡片圆角上看不出来）。
///
/// 唯一不参与收敛的例外：`widgets/audio_speaker_button.dart` 里两处
/// `Radius.circular(5)` / `Radius.circular(9)` 不是圆角，而是照抄原型 SVG
/// 弧线指令（`a5 5 0 0 1` / `a9 9 0 0 1`）的弧半径，换成造型台阶会画错喇叭。
///
abstract final class AppRadius {
  ///
  /// 2 · Tabler `$border-radius-sm` 那一档 · 进度条与细长条的圆角。
  ///
  /// 收敛前这一档写过 1 / 2 / 3 三种值，视觉上分不出来。
  ///
  /// 用在：
  /// - 四个学习模块 → 顶栏下方进度条 → 两端；
  /// - 听音辨义 → 题目卡顶部横向步骤条 → 每一段（收敛前是 1）；
  /// - 词义连连 → 顶部时间进度条 → 两端；
  /// - 随身听 → 顶部进度条 → 两端；
  /// - 首页 → 侧栏缓存进度条、复习模式卡底部进度条；
  /// - 首页 → 趋势图选中日期下方的短下划线；
  /// - 首页 → 打卡热力图图例的 7×7 小方块；
  /// - 首页 → 打卡热力图分布条（收敛前是 3）。
  static const double roundedSm = 2;

  ///
  /// 6 · Tabler `$border-radius`（基准档，class 就叫 `.rounded`）· 徽标、勾选框与小标签。
  ///
  /// 收敛前这一档写过 4 / 5 / 6 三种值。
  ///
  /// 用在：
  /// - 词性及含义面板 → 含义卡左侧词性徽标（`n.` / `adj.`）；
  /// - 看义选词 → 白卡第 1 行 → 「选择对应的单词」标签；
  /// - 全站 Tooltip 气泡；
  /// - 词义连连 → 右上角倒计时的点击热区；
  /// - 首页 → 单词行左侧多选勾选框、全选勾选框（收敛前是 5）；
  /// - 首页 → 侧栏版本号徽标（收敛前是 4）；
  /// - 首页 → 打卡热力图日期方格（收敛前是 5）；
  /// - 首页 → 词库抽屉里的单词条目（收敛前是 5）；
  /// - 听音辨义 → 候选卡左侧 A/B/C/D 序号徽标（收敛前是 5）；
  /// - 随身听 → 播放控制条上的小圆角按钮。
  static const double rounded = 6;

  ///
  /// 8 · Tabler `$border-radius-lg` 那一档 · 卡片与主按钮的圆角。
  ///
  /// 全站最常用的一档（收敛后 48 处）。
  ///
  /// 用在：
  /// - 听音辨义 → 中间题目白卡；
  /// - 拼写巩固 → 正文白卡；
  /// - 看义选词 → 正文白卡；
  /// - 听音辨义 → 底部「再试一次 / 下一题」两个按钮；
  /// - 首页 → 单词表单的输入框、按钮、分段控件（其中右半段收敛前是 7）；
  /// - 首页 → 搜索框、分组筛选条底板、侧栏各入口行；
  /// - 随身听 → 设置行与播放列表行；
  /// - 全站 Toast 气泡；
  /// - 听音辨义 → 底部四张候选卡（并进来的旧档 10）；
  /// - 看义选词 → 底部候选按钮（旧档 10）；
  /// - 词义连连 → 棋盘左右两列的候选卡（旧档 10）；
  /// - 四个模块 → 结算页统计卡与底部主按钮（旧档 10）；
  /// - 首页 → 侧栏顶部品牌 logo 的抗锯齿裁切（旧档 10）。
  static const double roundedLg = 8;

  ///
  /// 14 · Tabler `$border-radius-xl` 那一档 · 弹窗与底部面板的圆角。
  ///
  /// 用在：
  /// - 首页 → 删除单词确认弹窗；
  /// - 首页 → 添加 / 编辑单词的底部表单 → 顶部两角；
  /// - 首页 → 分组筛选条 → 展开后的分组面板；
  /// - 首页 → 单词表单 → 词性下拉菜单（收敛前是 15）；
  /// - 随身听 → 设置面板 → 顶部两角；
  /// - 首页 → 词库抽屉 → 顶部两角；
  /// - 词性及含义面板 → 每张含义卡（并进来的旧档 12，拼写巩固与听音辨义共用）。
  static const double roundedXl = 14;

  ///
  /// 20 · Tabler `$border-radius-xxl` 那一档 · 悬浮按钮与大面板的圆角。
  ///
  /// 用在：
  /// - 首页 → 右下角学习悬浮按钮及其展开面板（其中外框收敛前是 23）；
  /// - 首页 → 词库抽屉 → 顶部两角。
  static const double roundedXxl = 20;

  ///
  /// 胶囊形 · Tabler `.rounded-pill`：半径取一个足够大的值，让两端自动变成半圆。
  ///
  /// Tabler 那边写的是 `$border-radius-pill: 50rem`（800 像素），也是同一个套路
  /// ——不是真要 800 的圆角，而是「大到超过自身高度，两头就自动圆满」。
  ///
  /// 用在：
  /// - 播音胶囊 → 整个胶囊外框（听音辨义与拼写巩固共用）；
  /// - 字母格 → 下划线两端；
  /// - 词性及含义面板 → 待填含义的下划线两端；
  /// - 首页 → 词库抽屉 → 顶部拖拽条（收敛前写 5，与 5 高的条恰好同形）；
  /// - 首页 → 趋势图 → 选中日期的胶囊底；
  /// - 听音辨义 → 完成态「返回」按钮（StadiumBorder 同理）。
  static const double roundedPill = 999;
}

///
///
/// 全 App 的线宽刻度。
///
/// 这是唯一保留非整数的一组：1.5 与 2.5 是照 `ui/听音拼写1.html` 原型调出来的
/// 发丝线与下划线，改成 2 会让下划线明显变细、锚点白边糊掉，所以不参与偶数规则。
///
/// 「线宽」管两类东西：`Border` / `BorderSide` 的 `width`、`Paint` 的
/// `strokeWidth`，以及那种「本身就是一条线」的分隔条（1 像素粗的 Container）。
/// 不管的是光标宽度、连接线宽度这类**有自己造型语义**的细长方块，它们跟着
/// 各自的组件尺寸表走，改起来是改造型不是改线重。
///
abstract final class AppStroke {
  ///
  /// 1 · 普通描边与分隔线。
  ///
  /// 用在：
  /// - 全部卡片、候选按钮、统计卡的边框；
  /// - 词性徽标边框；
  /// - 首页 → 单词列表每行下方的分隔线；
  /// - 首页 → 批量操作条上方的分隔线；
  /// - 首页 → 词库抽屉 → 「继续 / 重新开始」之间的竖分隔线；
  /// - 首页 → 单词表单 → 虚线框的描边；
  /// - 首页 → 趋势图 → 底部横向基线；
  /// - 词性及含义面板 → 标题右侧那条横线。
  static const double thin = 1;

  ///
  /// 1.5 · 发丝线。
  ///
  /// 用在：
  /// - 词义连连 → 棋盘正中的竖直虚线；
  /// - 词义连连 → 锚点圆点外圈的白边；
  /// - 首页 → 单词行左侧多选勾选框的描边；
  /// - 首页 → 批量操作条上的全选勾选框描边；
  /// - 首页 → 趋势图 → 折线本体。
  static const double bold = 1.5;

  ///
  /// 2 · 加载转圈的圈厚度。
  ///
  /// 只有一个用处，但仍然给它一个名字：这条线不是边框也不是下划线，
  /// 而是「正在加载」那个转圈的粗细。单独列一档，是为了以后再加转圈时
  /// 有个现成的值可用，而不是随手又写一个数。
  ///
  /// 用在：
  /// - 首页 → 单词列表底部「加载更多」的转圈。
  static const double ring = 2;

  ///
  /// 2.5 · 填空下划线。
  ///
  /// 用在：
  /// - 拼写巩固 → 字母格下划线（一个字母一条）；
  /// - 看义选词 → 答案单词的字母格下划线（同一个组件）；
  /// - 词性及含义面板 → 待填含义下方的下划线。
  static const double mark = 2.5;
}
