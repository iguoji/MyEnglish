///
/// 全 App 的「造型尺寸」刻度：那些被多处共用的方寸。
///
/// 这张表管的是**组件外形**——一个用户看得见、点得到的方块有多宽多高：
/// 顶栏那一行的行高、进度条的粗细、序号方块的边长、结算页圆盘的直径。
/// 和另外几张表的分工是：
///
/// | 表 | 管什么 | 举例 |
/// |---|---|---|
/// | `AppSpace` | 两个东西之间的**空隙** | 卡片与卡片之间留 12 |
/// | `AppRadius` | 拐角的**弯度** | 卡片四角圆 8 |
/// | `AppStroke` | 线条的**粗细** | 边框 1、下划线 2.5 |
/// | `AppSize` | 方块本身的**方寸** | 顶栏行高 34、圆盘直径 64 |
///
/// 收录标准只有一条：**两个以上地方必须保持一致**。
///
/// 这一条是刻意收紧的。造型尺寸和间距不一样——间距是一整套视觉节奏，全站共用
/// 一把尺子是对的；而「40 高的圆形播放键」和「40 高的列表分组头」只是数字撞了，
/// 把它们并成同一个台阶，以后想把播放键调大一点，列表分组头会莫名跟着变高。
/// 所以只有一处用到的尺寸留在各自页面的尺寸表里——搬进总表不会让任何东西跟着变，
/// 只会让读者多跳一次。
///
/// 也因为这条标准，本表按**角色**命名而不是按数值：能进来的都是「同一个东西
/// 在多处出现」，名字说的就是那个东西。
///
abstract final class AppSize {
  ///
  /// 2 · 输入光标的粗细。
  ///
  /// 收进来的理由：三处各写了一遍 2，其中两处的注释还互相写着「改动时请同步」。
  /// 靠人记着同步的地方，迟早有一处会忘。
  ///
  /// 它不放进 `AppStroke`：那张表管的是边框、分隔线这类「真的是一条线」的东西，
  /// 光标是一个有自己造型语义的细长方块，归造型管。
  ///
  /// 用在：
  /// - 闪烁光标组件 → 默认粗细（`widgets/blinking_caret.dart`）；
  /// - 字母格 → 待输入位置的光标（拼写巩固与看义选词共用同一个组件）；
  /// - 词性及含义面板 → 待填含义位置的光标。
  static const double caretWidth = 2;

  ///
  /// 3 · 填空下划线获得焦点时，那圈淡蓝光晕的扩散宽度。
  ///
  /// 这是本表唯一的奇数，照抄原型的 `box-shadow: 0 0 0 3px`，不参与偶数规则。
  /// 两个方向都试过：改成 2 光晕基本看不出来，失去「下一笔落在这条线上」的提示
  /// 作用；改成 4 会和邻格的光晕连成一片——字母格之间只隔一档常规间隙
  /// （`AppSpace.p2` = 8），两侧各扩 4 正好把这道缝填满。3 是「看得清又不粘连」
  /// 的上限。
  ///
  /// 用在：
  /// - 字母格 → 当前待输入的那一条下划线；
  /// - 词性及含义面板 → 当前待填的那一条下划线。
  static const double underlineGlow = 3;

  ///
  /// 4 · 页面顶部时间进度条的粗细。
  ///
  /// 五个页面顶部都有这么一条，来回切换时粗细一变就会觉得页面在跳。
  /// 收敛前拼写巩固与词义连连是 3、其余是 4，现在统一成 4。
  ///
  /// 用在：
  /// - 随身听、听音辨义、拼写巩固、看义选词、词义连连 → 顶栏下方的进度条。
  static const double progressBar = 4;

  ///
  /// 18 · 勾选框的边长。
  ///
  /// 生活化解释：首页进入多选模式后，屏幕上会同时出现两种勾选框——每一行单词
  /// 左边一个、上方分组标题条上还有一个「整组全选」。两者是同一个控件，用户一眼
  /// 就能看到它们挨在一起，大小差一点都会显得歪。
  ///
  /// 收进来的理由：这两处原本在两张小表里各写了一遍 18，谁也不知道对方存在。
  ///
  /// 用在：
  /// - 首页 → 分组标题条 → 整组全选勾选框；
  /// - 首页 → 单词列表每一行 → 行首勾选框。
  static const double checkbox = 18;

  ///
  /// 16 · 输入光标的高度。
  ///
  /// 是字母格字母字号（24，见 [AppFont.fs1]）的三分之二：光标底边与字母底边
  /// 对齐同一条下划线，顶端只到字母三分之二处，不会盖住字母顶部、也不抢字母
  /// 的视觉焦点。曾与字母等高（24），用户反馈太高后整体压到 2/3。
  ///
  /// 用在：
  /// - 字母格 → 光标高度（字母格的文字区高度也取这一档）；
  /// - 词性及含义面板 → 光标高度**上限**：含义行比字母格矮，实际高度会按可用
  ///   空间收缩，这一档只封顶。
  static const double caretHeight = 16;

  ///
  /// 28 · 候选项左侧 A / B / C / D 序号方块的边长。
  ///
  /// 两个模块的候选项长得一样，序号方块必须同样大，否则来回切换时左边这一列
  /// 会忽大忽小。它是正方形，宽高都用这一个值。
  ///
  /// 用在：
  /// - 听音辨义 → 底部四张候选卡左侧的序号方块；
  /// - 看义选词 → 底部候选按钮左侧的序号方块。
  static const double optionBadge = 28;

  ///
  /// 34 · 练习页顶栏那一行的行高，同时也是返回按钮的点击方块边长。
  ///
  /// 生活化解释：这是一个 34×34 的不可见点击方块，手指点在方块内任意位置都能
  /// 触发返回，比图标本身大一圈，好按很多。
  ///
  /// 五个页面共用同一个值，为的是「切换模块时顶部严丝合缝、不产生跳动」。
  /// 这一行是写死高度，字号放大后里面的数字会跟着变高，所以
  /// `test/font_scale_pressure_test.dart` 会在每一档字号下量一次余量，
  /// 逼近 34 就直接判失败。
  ///
  /// 用在：
  /// - 随身听、听音辨义、拼写巩固、看义选词、词义连连 → 顶栏行高与返回按钮。
  static const double headerRow = 34;

  ///
  /// 40 · 图标按钮的点击方块边长。
  ///
  /// 生活化解释：一个 40×40 的不可见方块，中间放一个 20 的图标。方块比图标大
  /// 一圈，手指落在图标附近也能点中。
  ///
  /// 用在：
  /// - 首页 → 右上角打开抽屉的菜单按钮；
  /// - 首页 → 新增/编辑单词面板 → 右上角的关闭按钮。
  ///
  /// 它和下面的 [speakerButton] 数值相同、角色不同，所以刻意分成两档。本表按
  /// 角色命名就是为了这种情况：以后想把点击方块调大好按一点，播音圆盘不该跟着变。
  static const double iconHitBox = 40;

  ///
  /// 40 · 播音圆盘的直径。
  ///
  /// 生活化解释：拼写巩固与听音辨义都有一颗「点一下读给你听」的蓝色圆按钮，
  /// 两个模块前后脚出现，圆一大一小会很扎眼。
  ///
  /// 收进来的理由：这一档原先只写在拼写巩固的页面尺寸表里，公共组件
  /// `AudioSpeakerButton` 的默认直径又硬写着一遍 40，两处各说一遍同一件事。
  ///
  /// 用在：
  /// - 公共组件 `AudioSpeakerButton` → `size` 的默认值；
  /// - 拼写巩固 → 播放胶囊左侧的圆；
  /// - 听音辨义 → 释义阶段单词下方的播音圆。
  ///
  /// 遗留问题（不在本档范围内）：整颗「播放胶囊」——圆 + 声纹 + 状态文字——是
  /// 两个模块各画了一遍的重复代码，听音辨义那一份还直接引用了
  /// `SpellingLayout` 的十几个档位。真正的解法是把胶囊抽成公共组件、尺寸表跟着
  /// 搬到组件文件里，那是组件层的活儿，这里先把直径这一档归位。
  ///
  /// 例外：听音辨义**出题阶段**那颗大圆是 88（`questionSpeakerSize`），那一屏
  /// 只有它一个能点的东西，刻意做大，不走这一档。
  static const double speakerButton = 40;

  ///
  /// 44 · 手指可点的下限。
  ///
  /// 这一档不是某个组件的尺寸，而是一条规矩：可以点的东西不该矮于 44，
  /// 再矮就容易点不中。所以它总是以「最小高度」的身份出现，而不是写死高度——
  /// 写死高度会反过来把放大的文字压回去。
  ///
  /// 用在：
  /// - 看义选词 → 候选按钮的最小高度（标准字号下自然高度是 46，这一档只是底线）。
  static const double touchTarget = 44;

  ///
  /// 46 · 结算页底部主按钮的高度。
  ///
  /// 三个模块练完都会走到结算页，按钮高度不一致会让人觉得这是三个不同的 App。
  /// 46 仍然高于 [touchTarget] 那条下限。
  ///
  /// 用在：
  /// - 拼写巩固、看义选词、词义连连 → 结算页底部的主按钮。
  static const double summaryButton = 46;

  ///
  /// 52 · 一行设置项的行高。
  ///
  /// 生活化解释：抽屉里的「深色模式」「字号」这些行，和随身听设置面板里的
  /// 「语速」「间隔」这些行，是同一种东西——左边一句说明、右边一个开关或数字。
  /// 用户会先在抽屉里改一次、再进随身听改一次，行高不同会显得是两套界面。
  ///
  /// 用在：
  /// - 首页 → 抽屉 → 普通设置行；
  /// - 随身听 → 设置面板 → 每一项。
  static const double settingsRow = 52;

  ///
  /// 64 · 结算页顶部圆形图标底盘的直径。
  ///
  /// 里面那个庆祝图标是 24（`AppIcon.i24`），占直径的一半不到，四周还剩
  /// 20 的呼吸空间；图标顶到 32 就显得挤。
  ///
  /// 用在：
  /// - 拼写巩固、看义选词、词义连连 → 结算页顶部的圆形底盘；
  /// - 听音辨义 → 整轮完成页顶部那个绿色圆形对勾（它里面的图标用的是 32，
  ///   比另外三处大一档，但底盘直径必须一致，否则四个模块练完的收尾画面
  ///   会看着像四个不同的 App）。
  static const double summaryAvatar = 64;
}
